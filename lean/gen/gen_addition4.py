#!/usr/bin/env python3
"""Generate lean/Kissing4/Addition.lean: the solid addition theorem on R^3 for k <= KMAX, in the k!-scaled
normalisation of `Kissing4.Q4`:
  Zt_k(y,y') = sum_{m<=k} coefK k m * A_{k,m}(y) * A_{k,m}(y') * Rc_m(y,y'),
  Zt_0 = 1, Zt_1 = w, Zt_{k+2} = (2k+3) w Zt_{k+1} - (k+1)^2 g Zt_k,   w = <y,y'>, g = |y|^2 |y'|^2,
  Rc_0 = 1, Rc_1 = aa'+bb', Rc_{m+2} = 2 (aa'+bb') Rc_{m+1} - (a^2+b^2)(a'^2+b'^2) Rc_m  (= Re((a+ib)^m (a'-ib')^m)),
  A_{k,m}(a,b,c) = r^{k-m} P_k^{(m)}(c/r) (r^2 = a^2+b^2+c^2; a polynomial), coefK k m = k! c_{k,m} >= 0,
  c_{k,0} = 1, c_{k,m} = 2 (k-m)!/(k+m)!.  Every identity is checked with sympy before it is written.
usage: python3 lean/gen/gen_addition4.py [KMAX]"""
import math, os, sys
import sympy as sp

KMAX = int(sys.argv[1]) if len(sys.argv) > 1 else 7
a, b, c, a2, b2, c2, x = sp.symbols("a b c a2 b2 c2 x")
w = a * a2 + b * b2 + c * c2
g = (a**2 + b**2 + c**2) * (a2**2 + b2**2 + c2**2)
Z = [sp.Integer(1), w]
for k in range(KMAX - 1):
    Z.append(sp.expand((2 * k + 3) * w * Z[k + 1] - (k + 1) ** 2 * g * Z[k]))
R = [sp.Integer(1), a * a2 + b * b2]
for m in range(KMAX - 1):
    R.append(sp.expand(2 * (a * a2 + b * b2) * R[m + 1] - (a**2 + b**2) * (a2**2 + b2**2) * R[m]))


def A(k, m, X, Y, W):
    poly = sp.Poly(sp.expand(sp.diff(sp.legendre(k, x), x, m)), x)
    out = 0
    for (e,), co in poly.terms():
        assert (k - m - e) % 2 == 0
        out += co * W**e * (X**2 + Y**2 + W**2) ** ((k - m - e) // 2)
    return sp.expand(out)


def coef(k, m):
    return sp.Integer(math.factorial(k)) * (1 if m == 0 else sp.Rational(2 * math.factorial(k - m), math.factorial(k + m)))


def lean_expr(e, names):
    s = sp.sstr(sp.expand(e))
    for old, new in names:
        s = s.replace(old, new)
    return s.replace("**", "^")


for k in range(KMAX + 1):
    rhs = sum(coef(k, m) * A(k, m, a, b, c) * A(k, m, a2, b2, c2) * R[m] for m in range(k + 1))
    assert sp.expand(Z[k] - rhs) == 0, k
print(f"all identities k <= {KMAX} verified with sympy")

L = ["import Mathlib", "import Kissing4.Kernel  -- build order only: keeps `lake build` sequential on a shared machine", "",
     "/-! The solid addition theorem on `ℝ³` for degrees `k ≤ %d`, in the normalisation of `Kissing4.Q4`" % KMAX,
     "",
     "Generated by `lean/gen/gen_addition4.py` (every identity is first checked with sympy). Do not edit; regenerate.",
     "",
     "For `y = (a, b, c)`, `y' = (a', b', c')` the kernel `Zt k`, defined by the recursion of `Kissing4.Q4` in",
     "`w = ⟪y, y'⟫` and `g = ‖y‖² ‖y'‖²`, equals `∑_{m ≤ k} coefK k m · A k m y · A k m y' · Rc m`, where",
     "`Rc m = Re((a + i b)^m (a' - i b')^m)` (Chebyshev recursion), `A k m (a, b, c) = r^(k-m) P_k^(m)(c / r)`",
     "(`P_k` the Legendre polynomial, `r² = a² + b² + c²`; a polynomial in `c` and `r²`) and",
     "`coefK k m = k! · (m = 0 ? 1 : 2 (k-m)! / (k+m)!) ≥ 0`. -/", "",
     "namespace Kissing4", "",
     "/-- The `k!`-scaled solid Legendre kernel on `ℝ³`, by the recursion of `Q4`. -/",
     "noncomputable def Zt (a b c a' b' c' : ℝ) : ℕ → ℝ",
     "  | 0 => 1",
     "  | 1 => a * a' + b * b' + c * c'",
     "  | k + 2 => (2 * (k : ℝ) + 3) * (a * a' + b * b' + c * c') * Zt a b c a' b' c' (k + 1)",
     "      - ((k : ℝ) + 1) ^ 2 * ((a ^ 2 + b ^ 2 + c ^ 2) * (a' ^ 2 + b' ^ 2 + c' ^ 2)) * Zt a b c a' b' c' k", "",
     "/-- `Re((a + i b)^m (a' - i b')^m)`, by the Chebyshev recursion. -/",
     "noncomputable def Rc (a b a' b' : ℝ) : ℕ → ℝ",
     "  | 0 => 1",
     "  | 1 => a * a' + b * b'",
     "  | m + 2 => 2 * (a * a' + b * b') * Rc a b a' b' (m + 1) - (a ^ 2 + b ^ 2) * (a' ^ 2 + b' ^ 2) * Rc a b a' b' m", "",
     "/-- The polynomial factors `A k m (a, b, c) = r^(k-m) P_k^(m)(c / r)` for `m ≤ k ≤ %d` (`0` otherwise). -/" % KMAX,
     "noncomputable def Aa : ℕ → ℕ → ℝ → ℝ → ℝ → ℝ"]
for k in range(KMAX + 1):
    for m in range(k + 1):
        e = A(k, m, a, b, c)
        names = ["a" if e.has(a) else "_", "b" if e.has(b) else "_", "c" if e.has(c) else "_"]
        L.append(f"  | {k}, {m}, {', '.join(names)} => {lean_expr(e, [])}")
L += ["  | _, _, _, _, _ => 0", "",
      "/-- The coefficients `k! · c_{k,m}` for `m ≤ k ≤ %d` (`0` otherwise). -/" % KMAX,
      "noncomputable def coefK : ℕ → ℕ → ℝ"]
for k in range(KMAX + 1):
    for m in range(k + 1):
        L.append(f"  | {k}, {m} => {sp.sstr(coef(k, m))}")
L += ["  | _, _ => 0", "",
      "theorem coefK_nonneg (k m : ℕ) : 0 ≤ coefK k m := by",
      "  unfold coefK",
      "  split <;> norm_num", ""]
for k in range(KMAX + 1):
    L += [f"theorem Zt_addition_{k} (a b c a' b' c' : ℝ) :",
          f"    Zt a b c a' b' c' {k} = ∑ m ∈ Finset.range {k + 1},",
          f"      coefK {k} m * Aa {k} m a b c * Aa {k} m a' b' c' * Rc a b a' b' m := by",
          "  simp only [Finset.sum_range_succ, Finset.sum_range_zero, Zt, Rc, Aa, coefK]"]
    L += (["  push_cast"] if k >= 2 else []) + ["  ring", ""]
L += ["/-- **The addition theorem for `k ≤ %d`.** -/" % KMAX,
      "theorem Zt_addition {k : ℕ} (hk : k ≤ %d) (a b c a' b' c' : ℝ) :" % KMAX,
      "    Zt a b c a' b' c' k = ∑ m ∈ Finset.range (k + 1),",
      "      coefK k m * Aa k m a b c * Aa k m a' b' c' * Rc a b a' b' m := by",
      "  interval_cases k",
      ] + [f"  · exact Zt_addition_{k} a b c a' b' c'" for k in range(KMAX + 1)] + ["", "end Kissing4", ""]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Kissing4", "Addition.lean")
open(out, "w").write("\n".join(L))
print("wrote", os.path.normpath(out))
